import assert from "node:assert/strict";
import { createVoteStore } from "../server/votes.mjs";
import { compareLinkedBeforeAfter } from "../web/poll-analytics.js";

const store = createVoteStore();
const code = store.createSession();
const before = store.createPoll(code, { question: "ما تفسير التعزيز؟",
  options: ["الخيار الأول", "الخيار الثاني"], beforeAfter: true, correctIndex: 0, objective: "استيعاب مفهوم التعزيز" });
assert.equal(before.pulsePhase, "before");
assert.equal(before.correctIndex, 0);
store.setStatus(code, before.id, "open");
store.vote(code, "a".repeat(24), 0);
store.vote(code, "b".repeat(24), 1);
assert.throws(() => store.repeatBeforeAfterPoll(code,before.id));
store.setStatus(code, before.id, "closed");
assert.equal(Object.keys(before.votes).length, 0, "anonymized pulse must not retain device identifiers");
assert.deepEqual(before.archive,[1,1]);
assert.throws(() => store.setStatus(code,before.id,"open"));
const after = store.repeatBeforeAfterPoll(code,before.id);
assert.equal(after.pulsePhase, "after");
assert.deepEqual(after.options,before.options);
assert.equal(after.correctIndex,0);
assert.throws(() => store.repeatBeforeAfterPoll(code,before.id));
store.vote(code, "c".repeat(24), 0);
store.setStatus(code,after.id,"closed");
assert.equal(Object.keys(after.votes).length,0);
const state=store.presenterState(code);
assert.equal(state.polls[0].total,2);
assert.equal(state.polls[1].total,1);
assert.equal(JSON.stringify(state).includes("a".repeat(24)),false);
const differences=compareLinkedBeforeAfter(state.polls);
assert.equal(differences.length,1);
assert.deepEqual([differences[0].firstTotal,differences[0].lastTotal],[2,1]);
assert.equal(differences[0].values[0].firstPercent,50);
assert.equal(differences[0].values[0].lastPercent,100);
assert.equal(differences[0].values[0].deltaPoints,50);
assert.equal(differences[0].correctIndex,0);
assert.match(differences[0].warning,/محدود/);
assert.deepEqual(compareLinkedBeforeAfter([{...state.polls[0],pulsePhase:"before"}]),[]);
assert.deepEqual(compareLinkedBeforeAfter([{...state.polls[0]}, {...state.polls[1],options:["الثاني","الأول"]}]),[]);
const ordinary=store.createPoll(code,{question:"تصويت عادي",options:["أ","ب"]});
store.setStatus(code,ordinary.id,"open");
store.vote(code,"d".repeat(24),1);
store.setStatus(code,ordinary.id,"closed");
assert.equal(store.presenterState(code).polls.at(-1).total,1);
const words=store.createPoll(code,{question:"سحابة الكلمات",kind:"words"});
assert.equal(words.kind,"words");
assert.throws(() => store.createPoll(code,{question:"سحابة",kind:"words",beforeAfter:true}));
console.log("Cognitive Pulse 2.0 and ordinary vote regressions passed");
